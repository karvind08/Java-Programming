public class Default2 {
    public static void main(String[] args) {
        int a = 2;
        float b = 0.6f;
        double d = 4.56d;
        long l = 19;
        System.out.println("int value: " + a);
        System.out.println("float value: " + b);
        System.out.println("double value: " + d);
        System.out.println("long value: " + l);
    }

}
