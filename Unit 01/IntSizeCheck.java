public class IntSizeCheck {
    public static void main(String[] args) {
        System.out.println("The size of int in Bits: " + Integer.SIZE);
        System.out.println("The size of int in Bytes: " + Integer.BYTES);
        System.out.println("The min value of int: " + Integer.MIN_VALUE);
        System.out.println("The max value of int: " + Integer.MAX_VALUE);
        System.out.println("The size of byte: " + Byte.SIZE);
        System.out.println("The size of byte: " + Byte.BYTES);
        System.out.println("The size of short: " + Short.SIZE);
        System.out.println("The size of short: " + Short.BYTES);
        System.out.println("The size of short: " + Long.BYTES);
    }
}
